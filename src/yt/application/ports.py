"""Small contracts implemented by external-system adapters and test doubles."""

from collections.abc import Collection, Iterable, Iterator
from pathlib import Path
from threading import Event
from typing import Protocol

from yt.domain.downloads import DownloadRequest, Playlist
from yt.domain.events import EventSink
from yt.domain.music import Track
from yt.domain.settings import AppSettings


class AudioOutput(Protocol):
    def play(self, path: Path, volume: float) -> None: ...
    def pause(self) -> None: ...
    def resume(self) -> None: ...
    def seek(self, seconds: float, paused: bool = False) -> None: ...
    def position(self) -> float: ...
    def busy(self) -> bool: ...
    def set_volume(self, volume: float) -> None: ...
    def stop(self) -> None: ...
    def close(self) -> None: ...


class SettingsStore(Protocol):
    def load(self) -> AppSettings: ...
    def save(self, settings: AppSettings) -> None: ...


class PlaylistReader(Protocol):
    def fetch(self, url: str, cancel: Event, playlist_items: str | None = None) -> Playlist: ...


class DownloadBackend(Protocol):
    def download(self, request: DownloadRequest, events: EventSink, cancel: Event) -> None: ...


class LibraryReader(Protocol):
    def scan(
        self, folder: Path, excluded: Collection[str], cancel: Event
    ) -> tuple[list[Track], int]: ...


class ThumbnailReader(Protocol):
    def images(
        self, targets: Iterable[tuple[str, str | None]], cancel: Event
    ) -> Iterator[tuple[str, bytes]]: ...
